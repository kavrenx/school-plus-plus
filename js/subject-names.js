function shortSubjectName(value) {
  const source = String(value || "").trim();
  return SUBJECT_SHORT_NAMES.get(normalizeSubjectName(source)) || source;
}

function normalizeSubjectName(value) {
  return String(value || "")
    .trim()
    .toLocaleLowerCase("ru")
    .replace(/ё/g, "е")
    .replace(/\s+/g, " ");
}

